#!/usr/bin/env node
// @effect-diagnostics nodeBuiltinImport:off globalConsole:off - A synchronous build-time generator that writes tracked asset files.
// Writes every vector icon source from packages/shared/src/appIconArtwork.ts:
// Icon Composer text layers (solid in app-icon.icon, other designs in app-icon-<design>.icon),
// the repository logo, the iOS widget template mark, the Android notification mark and the
// DMG background marks. Run `vp run icons:sources`, then `vp run icons:export`.
import * as NodeFS from "node:fs";
import * as NodePath from "node:path";
import { APP_ICONS } from "@t3tools/contracts";
import {
  APP_ICON_ARTWORK,
  APP_ICON_MARK_VIEWBOX,
  renderAppIconPaths,
  renderAppIconSvg,
  renderVectorDrawable,
} from "@t3tools/shared/appIcons";

const CHANNEL_DIRECTORIES = ["assets/dev", "assets/nightly", "assets/prod"] as const;
const DMG_MARK =
  /<!-- (?:Official|App) mark[^>]*-->\s*<svg x="32"[^>]*(?:fill|color)="(#[0-9a-fA-F]+)"[^>]*>[\s\S]*?<\/svg>/;

function dmgMark(color: string): string {
  const inner = renderAppIconPaths(APP_ICON_ARTWORK.solid.mono, { currentColor: color });
  return `<!-- App mark generated by scripts/sync-app-icon-sources.ts. -->\n  <svg x="32" y="18" width="28" height="28" viewBox="${APP_ICON_MARK_VIEWBOX}" color="${color}">\n${inner}\n  </svg>`;
}

export function buildSourceFiles(repoRoot: string): Map<string, string | Buffer> {
  const files = new Map<string, string | Buffer>();
  const read = (relative: string) => NodeFS.readFileSync(NodePath.join(repoRoot, relative));

  for (const directory of CHANNEL_DIRECTORIES) {
    const base = `${directory}/app-icon.icon`;
    const baseAssets = NodeFS.readdirSync(NodePath.join(repoRoot, base, "Assets"));
    for (const design of APP_ICONS) {
      const project = design === "solid" ? base : `${directory}/app-icon-${design}.icon`;
      files.set(`${project}/Assets/text.svg`, renderAppIconSvg(APP_ICON_ARTWORK[design].color));
      if (design === "solid") continue;
      files.set(`${project}/icon.json`, read(`${base}/icon.json`));
      for (const asset of baseAssets) {
        if (asset !== "text.svg") {
          files.set(`${project}/Assets/${asset}`, read(`${base}/Assets/${asset}`));
        }
      }
    }
  }

  files.set(
    "assets/prod/logo.svg",
    renderAppIconSvg(APP_ICON_ARTWORK.solid.color).replace(
      /(<svg[^>]*>\n)/,
      '$1  <path d="M0 10C0 4.47715 4.47715 0 10 0H118C123.523 0 128 4.47715 128 10V118C128 123.523 123.523 128 118 128H10C4.47715 128 0 123.523 0 118V10Z" fill="black"/>\n',
    ),
  );

  // The widget draws this template in a 3:2 frame (AgentActivity.tsx), so the keycap is
  // centered in a 3:2 viewBox instead of being stretched.
  files.set(
    "apps/mobile/assets/widget/T3Mark.svg",
    renderAppIconSvg(APP_ICON_ARTWORK.solid.mono, {
      viewBox: "-11 14 150 100",
      width: 150,
      height: 100,
      currentColor: "black",
    }),
  );
  files.set(
    "apps/mobile/modules/t3-agent-notifications/android/src/main/res/drawable/agent_activity_mark.xml",
    renderVectorDrawable(APP_ICON_ARTWORK.solid.mono, { color: "#FFFFFFFF", sizeDp: 24 }),
  );

  for (const channel of ["latest", "nightly"] as const) {
    const relative = `apps/desktop/resources/dmg/dmg-background-${channel}.svg`;
    const source = read(relative).toString("utf8");
    const match = DMG_MARK.exec(source);
    if (!match) throw new Error(`No mark block found in ${relative}.`);
    const color = match[1]!;
    files.set(
      relative,
      source
        .replace(DMG_MARK, () => dmgMark(color))
        .replace("Drag T3 Code into Applications.", "Drag Ctrl into Applications."),
    );
  }
  return files;
}

if (import.meta.main) {
  const repoRoot = NodePath.resolve(import.meta.dirname, "..");
  const files = buildSourceFiles(repoRoot);
  const check = process.argv.includes("--check");
  const stale: string[] = [];
  for (const [relative, contents] of files) {
    const target = NodePath.join(repoRoot, relative);
    const expected = typeof contents === "string" ? Buffer.from(contents) : contents;
    const current = NodeFS.existsSync(target) ? NodeFS.readFileSync(target) : null;
    if (current !== null && current.equals(expected)) continue;
    if (check) {
      stale.push(relative);
      continue;
    }
    NodeFS.mkdirSync(NodePath.dirname(target), { recursive: true });
    NodeFS.writeFileSync(target, expected);
    console.log(`wrote ${relative}`);
  }
  if (stale.length > 0) {
    console.error(`Stale icon sources:\n${stale.map((path) => `- ${path}`).join("\n")}`);
    process.exit(1);
  }
}
