#!/usr/bin/env node
// @effect-diagnostics nodeBuiltinImport:off globalConsole:off - Build-time font conversion script.
// Converts the keycap legends to vector paths so no client needs the font at runtime.
// Font: DM Sans (SIL Open Font License 1.1), from apps/mobile's @expo-google-fonts/dm-sans.
import * as NodeFS from "node:fs";
import * as NodePath from "node:path";

import type { AppIconLegends } from "@t3tools/shared/appIconArtwork";
import { loadFont, resolveDmSansFont, textToPath, type DmSansWeight } from "./lib/font-paths.ts";

const repoRoot = NodePath.resolve(import.meta.dirname, "..");
const OUTPUT = "packages/shared/src/appIconLegends.generated.ts";

const font = (weight: DmSansWeight) =>
  loadFont(NodeFS.readFileSync(resolveDmSansFont(repoRoot, weight)));

export function generateLegends(): AppIconLegends {
  return {
    outlineCtrl: textToPath(font("600SemiBold"), "ctrl", { size: 21, x: 35, baseline: 86 }),
    solidCtrl: textToPath(font("700Bold"), "ctrl", {
      size: 25,
      x: 64,
      baseline: 66,
      anchor: "middle",
    }),
    macControl: textToPath(font("500Medium"), "control", { size: 15, x: 30, baseline: 90 }),
  };
}

export function renderLegendsModule(legends: AppIconLegends): string {
  return [
    "// Generated by scripts/generate-app-icon-legends.ts from DM Sans (SIL OFL 1.1). Do not edit.",
    'import type { AppIconLegends } from "./appIconArtwork.ts";',
    "",
    "export const APP_ICON_LEGENDS: AppIconLegends = {",
    ...Object.entries(legends).map(([key, value]) => `  ${key}:\n    ${JSON.stringify(value)},`),
    "};",
    "",
  ].join("\n");
}

if (import.meta.main) {
  const target = NodePath.join(repoRoot, OUTPUT);
  const contents = renderLegendsModule(generateLegends());
  if (process.argv.includes("--check")) {
    const current = NodeFS.existsSync(target) ? NodeFS.readFileSync(target, "utf8") : "";
    if (current !== contents) {
      console.error(`${OUTPUT} is stale. Run: node scripts/generate-app-icon-legends.ts`);
      process.exit(1);
    }
    console.log(`${OUTPUT} is current.`);
  } else {
    NodeFS.writeFileSync(target, contents);
    console.log(`wrote ${OUTPUT}`);
  }
}
